/**
 * Get Anthropic client - real or simulated based on environment
 */
export function getAnthropicClient(apiKey?: string): Anthropic {
  const shouldSimulate = process.env.SIMULATE_ANTHROPIC === 'true';

  if (shouldSimulate) {
    console.log('🎭 Anthropic simulation mode enabled');
    return new MockAnthropic() as unknown as Anthropic;
  }

  // Use real client
  return new Anthropic({
    apiKey: apiKey || process.env.ANTHROPIC_API_KEY,
  });
}

/**
 * Check if we're in simulation mode
 */
export function isSimulationMode(): boolean {
  return process.env.SIMULATE_ANTHROPIC === 'true';
}
