class MockAnthropicStream {
  private response: string;
  private index: number = 0;
  private chunkSize: number = 50;

  constructor(response: string) {
    this.response = response;
  }

  async *[Symbol.asyncIterator]() {
    // Simulate streaming by chunking the response
    while (this.index < this.response.length) {
      const chunk = this.response.slice(this.index, this.index + this.chunkSize);
      this.index += this.chunkSize;

      yield {
        type: 'content_block_delta',
        delta: {
          type: 'text_delta',
          text: chunk,
        },
      };

      // Simulate network delay
      await new Promise(resolve => setTimeout(resolve, 50));
    }

    // Send final message
    yield {
      type: 'message_stop',
      message: {
        stop_reason: 'end_turn',
        usage: {
          input_tokens: 100,
          output_tokens: this.response.length / 4, // Rough estimate
        },
      },
    };
  }

  async finalMessage() {
    return {
      id: `sim_${Date.now()}`,
      type: 'message',
      role: 'assistant',
      content: [{ type: 'text', text: this.response }],
      model: 'claude-3-5-sonnet-20241022',
      stop_reason: 'end_turn',
      usage: {
        input_tokens: 100,
        output_tokens: this.response.length / 4,
      },
    };
  }
}

